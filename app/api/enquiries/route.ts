import { NextRequest } from "next/server";
import { z } from "zod";
import { nextEnquiryReference } from "@/lib/enquiry-reference";
import { deliverEnquiryNotification } from "@/lib/enquiry-notifications";
import connectDB from "@/lib/mongodb";
import Enquiry from "@/models/Enquiry";
import { successResponse, errorResponse, handleApiError } from "@/lib/api-response";
import { AttachmentError, deleteEnquiryAttachment, readLimitedBody, uploadEnquiryAttachment, type EnquiryAttachment } from "@/lib/enquiry-attachments";
import { MAX_ENQUIRY_ATTACHMENT_BYTES, validateEnquiryAttachment } from "@/lib/enquiry-attachment-validation";

const enquirySubmitSchema = z.object({
  businessLine: z.string().default("general"),
  fullName: z.string().min(2, "Full name must be at least 2 characters").max(120),
  companyName: z.string().min(2, "Company name must be at least 2 characters").max(150),
  workEmail: z.string().email("Invalid email address"),
  phone: z.string().min(6, "Phone number must be at least 6 characters").max(30),
  location: z.string().min(2, "Location is required").max(100),
  requirement: z.string().min(10, "Requirement must be at least 10 characters").max(4000),
  // Attachment metadata is generated by the server after upload, never accepted from the browser.
  attachmentUrl: z.never().optional(),
  attachmentPublicId: z.never().optional(),
});

export async function POST(request: NextRequest) {
  let attachment: EnquiryAttachment | undefined;
  let saved = false;
  try {
    const contentType = request.headers.get("content-type") || "";
    const limit = contentType.includes("multipart/form-data") ? MAX_ENQUIRY_ATTACHMENT_BYTES + 64 * 1024 : 64 * 1024;
    if (Number(request.headers.get("content-length")) > limit) {
      return errorResponse("Request exceeds the allowed upload size", 413);
    }
    const bytes = await readLimitedBody(request.body, limit);
    let body: unknown;
    let file: File | undefined;
    if (contentType.includes("multipart/form-data")) {
      let form: FormData;
      try {
        form = await new Response(new Uint8Array(bytes), { headers: { "content-type": contentType } }).formData();
      } catch { return errorResponse("Invalid multipart form data", 400); }
      const files = [...form.values()].filter((value): value is File => value instanceof File);
      const candidate = form.get("attachment");
      if (files.length > 1 || (files.length === 1 && !(candidate instanceof File))) {
        return errorResponse("Submit one file using the attachment field", 422);
      }
      if (candidate instanceof File) {
        const validation = validateEnquiryAttachment(candidate);
        if (!validation.valid) return errorResponse(validation.error, 422);
        file = candidate;
      }
      body = Object.fromEntries([...form.entries()].filter(([, value]) => typeof value === "string"));
    } else if (contentType.includes("application/json")) {
      body = JSON.parse(bytes.toString("utf8"));
    } else { return errorResponse("Expected multipart/form-data or application/json", 415); }
    const validated = enquirySubmitSchema.parse(body);

    await connectDB();

    if (file) attachment = await uploadEnquiryAttachment(file);
    const referenceId = await nextEnquiryReference();

    const enquiry = await Enquiry.create({
      referenceId,
      businessLine: validated.businessLine,
      fullName: validated.fullName,
      companyName: validated.companyName,
      workEmail: validated.workEmail.toLowerCase(),
      phone: validated.phone,
      location: validated.location,
      requirement: validated.requirement,
      ...attachment,
      status: "new",
    });
    saved = true;

    try {
      await deliverEnquiryNotification(enquiry._id.toString());
    } catch {
      console.error("Enquiry saved; notification needs review", { referenceId });
    }

    return successResponse(
      {
        referenceId: enquiry.referenceId,
        id: enquiry._id.toString(),
        message: "Enquiry submitted successfully",
      },
      201
    );
  } catch (error) {
    if (attachment && !saved) {
      await deleteEnquiryAttachment(attachment).catch(() => console.error("Failed to clean up unsaved enquiry attachment"));
    }
    if (error instanceof AttachmentError) return errorResponse(error.message, error.status);
    return handleApiError(error);
  }
}
